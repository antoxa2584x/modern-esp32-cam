# Pre-build step: gzips every file in web/ into src/web_assets.h, so the UI is
# served straight from flash (no filesystem image to upload separately).
import gzip
import hashlib
import os
import re

Import("env")  # noqa: F821 (provided by PlatformIO)

ROOT = env.subst("$PROJECT_DIR")  # noqa: F821
WEB = os.path.join(ROOT, "web")
OUT = os.path.join(ROOT, "src", "web_assets.h")

MIME = {
    ".html": "text/html; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".js": "application/javascript; charset=utf-8",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
    ".webmanifest": "application/manifest+json",
}


# index.html names its scripts and styles with ?v=<hash of all of them>. Through
# the relay, Cloudflare tells browsers to keep .js/.css for 4 hours whatever the
# camera says, so after an update phones kept running the old app.js.
def versioned_index(raw, files):
    h = hashlib.sha1()
    for name in files:
        if name != "index.html":
            h.update(open(os.path.join(WEB, name), "rb").read())
    v = h.hexdigest()[:10]
    html = raw.decode("utf-8")
    html = re.sub(r'((?:src|href)=")((?:app|i18n)\.(?:js|css))"', lambda m: f'{m.group(1)}{m.group(2)}?v={v}"', html)
    return html.encode("utf-8")


def build():
    files = sorted(f for f in os.listdir(WEB) if os.path.isfile(os.path.join(WEB, f)))
    lines = ["// Generated by scripts/embed_web.py from web/. Do not edit.", "#pragma once",
             "#include <stdint.h>", "#include <stddef.h>", ""]
    entries = []
    digest = hashlib.sha1()
    for i, name in enumerate(files):
        raw = open(os.path.join(WEB, name), "rb").read()
        if name == "index.html":
            raw = versioned_index(raw, files)
        data = gzip.compress(raw, 9, mtime=0)
        digest.update(data)
        lines.append(f"static const uint8_t WEB_{i}[] = {{")
        for off in range(0, len(data), 24):
            lines.append("  " + ",".join(str(b) for b in data[off:off + 24]) + ",")
        lines.append("};")
        mime = MIME.get(os.path.splitext(name)[1], "application/octet-stream")
        entries.append(f'  {{"/{name}", "{mime}", WEB_{i}, sizeof(WEB_{i})}},')
    lines += ["", "struct WebAsset { const char* path; const char* mime; const uint8_t* data; size_t len; };",
              "static const WebAsset WEB_ASSETS[] = {"] + entries + ["};",
              f"static const size_t WEB_ASSET_COUNT = {len(files)};",
              f'static const char WEB_ETAG[] = "\\"{digest.hexdigest()[:16]}\\"";', ""]
    text = "\n".join(lines)
    if not os.path.exists(OUT) or open(OUT).read() != text:
        open(OUT, "w", newline="\n").write(text)
        print("embed_web: wrote", OUT)


build()
