// Interface language. The Ukrainian text in app.js is the key; EN below holds
// the English for each key. A key missing from EN shows in Ukrainian.
// Loaded before app.js (and demo.js).

const LANGS = ['uk', 'en'];
const LANG = (() => {
    let saved = null;
    try { saved = localStorage.getItem('lang'); } catch (e) { /* private mode */ }
    if (LANGS.includes(saved)) return saved;
    for (const l of navigator.languages || [navigator.language || '']) {
        const code = String(l).slice(0, 2).toLowerCase();
        if (code === 'uk' || code === 'ru') return 'uk';
        if (code === 'en') return 'en';
    }
    return 'uk';
})();
const LOCALE = LANG === 'en' ? 'en-GB' : 'uk-UA';
document.documentElement.lang = LANG;

function setLang(lang) {
    try { localStorage.setItem('lang', lang); } catch (e) { /* private mode */ }
    location.reload();
}

// t('Видалено {n} {u}', { n: 3, u: ... })
function t(uk, vars) {
    let s = LANG === 'en' && EN[uk] !== undefined ? EN[uk] : uk;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
    return s;
}

// Counted words: pl(5, 'rec') -> "записів" / "recordings"
const PLURALS = {
    rec: [['запис', 'записи', 'записів'], ['recording', 'recordings']],
    min: [['хвилину', 'хвилини', 'хвилин'], ['minute', 'minutes']],
    hour: [['годину', 'години', 'годин'], ['hour', 'hours']],
    day: [['день', 'дні', 'днів'], ['day', 'days']],
    net: [['мережу', 'мережі', 'мереж'], ['network', 'networks']],
};
function pl(n, key) {
    const [uk, en] = PLURALS[key];
    if (LANG === 'en') return Math.abs(n) === 1 ? en[0] : en[1];
    const a = Math.abs(n) % 100, b = a % 10;
    if (a > 10 && a < 20) return uk[2];
    if (b > 1 && b < 5) return uk[1];
    if (b === 1) return uk[0];
    return uk[2];
}

